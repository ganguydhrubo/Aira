package com.ganguydhrubo.aira.core.docs

import com.ganguydhrubo.aira.core.learn.knowledge.IndexEntry
import com.ganguydhrubo.aira.core.learn.knowledge.KnowledgeIndex
import java.io.File

/**
 * The README lists that change with the code (built-in knowledge, provider presets) are generated from their sources and
 * sit between `<!-- generated:<name>:start -->` and `<!-- generated:<name>:end -->`.
 * `./gradlew updateReadme` rewrites README.md; core's `ReadmeSectionsTest` checks it matches. Translations carry no generated sections.
 *
 * The knowledge list uses the same [KnowledgeIndex.build] as the build index, in index order. Provider presets live in the
 * app's `ProviderPresets.kt`, which core can't load, so each `ProviderPreset("name", ProviderConfig.Kind.<kind>, "url"` is read
 * from source; the app's `ReadmePresetsTest` compares against the real `ProviderPresets.all` and fails if this parsing falls behind.
 */
object ReadmeSections {
    /** The repository front page, in English, and the source of every translation. */
    const val README = "README.md"
    const val KNOWLEDGE = "knowledge"
    const val PROVIDERS = "providers"
    const val RESOURCES = "core/src/main/resources"
    const val PRESETS_SOURCE = "app/src/main/java/com/ganguydhrubo/aira/settings/ProviderPresets.kt"
    private const val NOTE_EN = "<!-- Generated by ./gradlew updateReadme; do not edit by hand -->"

    fun start(name: String) = "<!-- generated:$name:start -->"
    fun end(name: String) = "<!-- generated:$name:end -->"

    /** One preset from source; [kind] is the `ProviderConfig.Kind` enum name, and an empty [baseUrl] means "Custom". */
    data class Preset(val label: String, val kind: String, val baseUrl: String)

    private val PRESET = Regex("""ProviderPreset\(\s*"([^"]+)"\s*,\s*ProviderConfig\.Kind\.(\w+)\s*,\s*"([^"]*)"""")

    fun presets(source: String): List<Preset> =
        PRESET.findAll(source).map { Preset(it.groupValues[1], it.groupValues[2], it.groupValues[3]) }.toList()

    private fun kindNameEn(kind: String) = when (kind) { "OpenAiCompat" -> "OpenAI-compatible"; "OpenAiResponses" -> "OpenAI Responses"; else -> kind }

    /** Endpoint kinds "Custom" accepts: those used by presets, Responses last, matching the screen order (`ProviderConfig.Kind.withApiKey`). */
    private fun customKinds(presets: List<Preset>) = presets.map { it.kind }.distinct().sortedBy { it == "OpenAiResponses" }

    /** "a, b or c". */
    private fun orList(items: List<String>) =
        if (items.size <= 1) items.joinToString() else items.dropLast(1).joinToString(", ") + " or " + items.last()

    fun knowledgeEn(entries: List<IndexEntry>): String {
        fun names(kind: String) = entries.filter { it.kind == kind }.joinToString(", ") { it.display }
        return listOf(
            NOTE_EN,
            "| Category | Built in |",
            "|---|---|",
            "| **Apps** | ${names(KnowledgeIndex.APP)} |",
            "| **Websites** | ${names(KnowledgeIndex.SITE)} |",
            "| **How-to skills** | ${names(KnowledgeIndex.SKILL)} |",
        ).joinToString("\n")
    }

    /** One sentence: which presets exist (the empty-URL "Custom" one excluded) and which endpoint kinds Custom accepts. */
    fun providersEn(presets: List<Preset>): String {
        val names = presets.filter { it.baseUrl.isNotEmpty() }.joinToString(", ") { it.label }
        val custom = presets.firstOrNull { it.baseUrl.isEmpty() }?.label
        val kinds = orList(customKinds(presets).map { kindNameEn(it) })
        val pick = if (custom == null || custom == "Custom") "Custom" else "Custom ($custom)"
        return listOf(NOTE_EN, "Presets for $names and more; for any other provider pick $pick, which takes any $kinds endpoint.").joinToString("\n")
    }

    /** What each section under repository root [root] should contain. */
    fun sections(root: File): Map<String, String> {
        val index = KnowledgeIndex.build(File(root, RESOURCES))
        check(index.errors.isEmpty()) { "Built-in knowledge failed validation:\n" + index.errors.joinToString("\n") }
        val presets = presets(File(root, PRESETS_SOURCE).readText())
        check(presets.isNotEmpty()) { "No ProviderPreset found in $PRESETS_SOURCE" }
        return mapOf(KNOWLEDGE to knowledgeEn(index.entries), PROVIDERS to providersEn(presets))
    }

    /** Replaces the text between each pair of markers in [readme]; fails when markers are missing or out of order. */
    fun render(readme: String, sections: Map<String, String>): String =
        sections.entries.fold(readme) { text, (name, body) ->
            val s = text.indexOf(start(name))
            val e = text.indexOf(end(name))
            check(s >= 0 && e > s) { "README is missing ${start(name)} … ${end(name)}" }
            text.substring(0, s + start(name).length) + "\n" + body + "\n" + text.substring(e)
        }

    /** Entry point for `updateReadme`: `<repository root>`. */
    @JvmStatic
    fun main(args: Array<String>) {
        val root = File(args[0])
        val file = File(root, README)
        val before = file.readText()
        val after = render(before, sections(root))
        if (after != before) file.writeText(after)
        println(if (after != before) "$README updated" else "$README already up to date")
    }
}
